// Independent wire fixtures — MEASURED with the client's own codec
// (bedrock-codec-3.0.0.Beta13, org.cloudburstmc.protocol.bedrock.data.SubChunkRequestResult):
//
//	0=UNDEFINED 1=SUCCESS 2=CHUNK_NOT_FOUND 3=INVALID_DIMENSION
//	4=PLAYER_NOT_FOUND 5=INDEX_OUT_OF_BOUNDS 6=SUCCESS_ALL_AIR
//
// The fork's SubChunkResult* constants match that list 1:1 ⇒ the wire value IS the internal one,
// do NOT translate. The earlier claim ("2193 wire is 0..5, Undefined was removed") is disproven:
// SUCCESS(1) written as 0 ⇒ the client reads UNDEFINED ⇒ the sub-chunk is skipped.
func TestSubChunk2193ResultWire(t *testing.T) {
	for result := byte(0); result <= 6; result++ {
		entry := protocol.SubChunkEntry{Result: result}
		var buf bytes.Buffer
		entry.Marshal(minecraft.DefaultProtocol.NewWriter(&buf, 0))
		want := []byte{0, 0, 0, result, 0, 0, 0, 0, 0, 0}
		if !bytes.Equal(buf.Bytes(), want) {
			t.Errorf("result %d wire=%x want=%x", result, buf.Bytes(), want)
		}
		if entry.Result != result {
			t.Fatal("writer mutated canonical result")
		}
		var decoded protocol.SubChunkEntry
		decoded.Marshal(minecraft.DefaultProtocol.NewReader(bytes.NewReader(want), 0, false))
		if decoded.Result != result {
			t.Errorf("wire result %d decoded=%d want=%d", result, decoded.Result, result)
		}
	}
}

// The relay verifies canonical host packets before the client's converter runs.
// A 1001 request sentinel must not cause valid terrain to be dropped.
func TestVerifyLegacyRequestForModernClient(t *testing.T) {
	pk := &packet.LevelChunk{SubChunkCount: 0xfffffffe, SubChunkLimit: protocol.Option(int32(8)), RawPayload: []byte{0, 0}}
	for _, id := range []int32{1001, 2168, 2169, 2193} {
		codec, _ := resolveProto(id)
		if err := verifyRoundTrip(pk, codec); err != nil {
			t.Errorf("client%d: %v", id, err)
		}
	}
	if pk.SubChunkCount != 0xfffffffe {
		t.Fatal("diagnostic mutated source packet")
	}
}

func TestAuditRecognisesHashedPalette(t *testing.T) {
	oldOn, oldBad := auditOn, auditBadIDs
	auditOn, auditBadIDs = true, 0
	defer func() { auditOn, auditBadIDs = oldOn, oldBad }()
	// Hash IDs copied from the latest live log, not generated by the mapper.
	ids := []uint32{299238750, 4121722107, 685383673, 3385275638}
	var payload bytes.Buffer
	payload.Write([]byte{9, 1, 0, 5}) // v9, 1 layer, Y=0, 2 bits/network palette.
	payload.Write(make([]byte, 1024))
	_ = protocol.WriteVarint32(&payload, int32(len(ids)))
	for _, id := range ids {
		_ = protocol.WriteVarint32(&payload, int32(id))
	}
	pk := &packet.SubChunk{SubChunkEntries: []protocol.SubChunkEntry{{Result: protocol.SubChunkResultSuccess, RawPayload: protocol.Option(payload.Bytes())}}}
	auditSubChunk(pk, 2193, true)
	if auditBadIDs != 0 {
		t.Fatalf("valid hash palette reported %d invalid IDs", auditBadIDs)
	}
}
